/**
 * SDL → classified-variant pipeline tests for the node-id path: input-side carriers with
 * {@link no.sikt.graphitron.rewrite.model.CallSiteExtraction.NodeIdDecodeKeys}, output-side
 * {@link ChildField.ColumnBackedField} / {@link ChildField.ColumnBackedReferenceField} with
 * {@link no.sikt.graphitron.rewrite.model.CallSiteCompaction.NodeIdEncodeKeys}, and type-level
 * {@link GraphitronType.NodeType} synthesis for tables whose jOOQ class exposes
 * {@code __NODE_TYPE_ID} + {@code __NODE_KEY_COLUMNS} constants, plus the SDL-declared
 * {@code @node} / {@code @nodeId} directive paths.
 *
 * <p>Uses the {@code no.sikt.graphitron.rewrite.nodeidfixture} catalog, generated by
 * {@code NodeIdFixtureGenerator} in {@code graphitron-fixtures-codegen} as a faithful model of
 * Sikt's production {@code KjerneJooqGenerator}, so the classifier sees real generator output.
 * <ul>
 *   <li>{@code bar}: composite-key NodeType; {@code __NODE_TYPE_ID = "Bar"},
 *       {@code __NODE_KEY_COLUMNS = { BAR.ID_1, BAR.ID_2 }}. FK {@code bar.id_1 -> baz.id}
 *       supports composite-key reference tests.</li>
 *   <li>{@code baz}: single-key NodeType; reference target for {@code bar}.</li>
 *   <li>{@code qux}: plain table, no metadata; negative-case fixture.</li>
 *   <li>{@code parent_node}: single-key NodeType keyed on {@code PK_ID}, with a separate unique
 *       {@code ALT_KEY} targeted by {@code child_ref.parent_alt_key}'s FK. The FK target does
 *       not positionally match the keyColumn, forcing the rooted-at-parent
 *       JOIN-with-projection path.</li>
 *   <li>{@code child_ref}: plain table; FK {@code parent_alt_key -> parent_node.alt_key} drives
 *       the rooted-at-parent fixtures.</li>
 *   <li>{@code shared_node}: single-key NodeType whose {@code __NODE_TYPE_ID} is the customized
 *       numeric {@code "10154"} (distinct from any GraphQL type name); paired with a {@code @node}
 *       plus a nesting-projection {@code @table} type to pin that the decode helper resolves
 *       through the {@code @node}-only {@link NodeIndex} ({@code decode<TypeName>}), not the
 *       typeId fallback ({@code decode10154}).</li>
 * </ul>
 */
