/**
 * Generates the {@code ErrorRouter} class emitted at
 * {@code <outputPackage>.schema.ErrorRouter}, once per code-generation run: the runtime
 * entry points the per-fetcher try/catch wrappers call ({@code redact},
 * {@code surfaceClientErrorOrRedact}, {@code dispatch}), the {@code toConfiguredLog} guard
 * every unmatched-exception log site hands its throw through, plus the nested {@code Mapping}
 * taxonomy the dispatch arms match against. Per-method
 * contracts live in the emitted javadoc (the {@code addJavadoc} strings below).
 *
 * <p>Dispatch is source-direct: the matched throwable itself goes into the errors list,
 * and graphql-java's {@code PropertyDataFetcher} reads each declared {@code @error}
 * field off it. Per-channel {@code Mapping[]} constants live on the per-package class
 * generated by {@link ErrorMappingsClassGenerator}.
 */
public final class ErrorRouterClassGenerator {

    public static final String CLASS_NAME = "ErrorRouter";
    public static final String MAPPING_INTERFACE = "Mapping";
    public static final String EXCEPTION_MAPPING = "ExceptionMapping";
    public static final String SQL_STATE_MAPPING = "SqlStateMapping";
    public static final String VENDOR_CODE_MAPPING = "VendorCodeMapping";

    private static final ClassName THROWABLE                  = ClassName.get(Throwable.class);
    private static final ClassName SQL_EXCEPTION              = ClassName.get("java.sql", "SQLException");
    private static final ClassName DATA_FETCHING_ENVIRONMENT  = ClassName.get("graphql.schema", "DataFetchingEnvironment");
    private static final ClassName DATA_FETCHER_RESULT        = ClassName.get("graphql.execution", "DataFetcherResult");
    private static final ClassName GRAPHQL_ERROR_BUILDER      = ClassName.get("graphql", "GraphqlErrorBuilder");
    private static final ClassName UUID_CN                    = ClassName.get(UUID.class);
    private static final ClassName LOGGER_CN                  = ClassName.get("org.slf4j", "Logger");
    private static final ClassName LOGGER_FACTORY_CN          = ClassName.get("org.slf4j", "LoggerFactory");
    private static final ClassName LIST_CN                    = ClassName.get(List.class);
    private static final ClassName STRING_CN                  = ClassName.get(String.class);
    private static final ClassName OBJECT_CN                  = ClassName.get(Object.class);
    private static final ClassName GRAPHQL_CONTEXT            = ClassName.get("graphql", "GraphQLContext");
    private static final ClassName CONSUMER_CN                = ClassName.get(Consumer.class);

    private ErrorRouterClassGenerator() {}

    /**
     * The emitted {@code ErrorRouter} class, resolved through the plan's naming vocabulary. The
     * error family reads its generated class names from here and from
     * {@link ErrorMappingsClassGenerator#mappingsClass} rather than re-deriving
     * {@code outputPackage + ".schema"} at each site.
     */
    public static ClassName routerClass(String outputPackage) {
        var unit = new no.sikt.graphitron.plan.GeneratedUnits(outputPackage).errorRouter();
        return ClassName.get(unit.packageName(), unit.simpleName());
    }

    /**
     * The emitted {@code FetcherErrorLog} interface, a {@code CONNECTION_RUNTIME} unit that
     * {@code toConfiguredLog} names; resolved through the plan's naming vocabulary like the router.
     */
    public static ClassName fetcherErrorLogClass(String outputPackage) {
        var unit = new no.sikt.graphitron.plan.GeneratedUnits(outputPackage)
            .singleton(no.sikt.graphitron.plan.GeneratedUnits.SUB_SCHEMA,
                no.sikt.graphitron.rewrite.generators.util.ConnectionRuntimeClassGenerator.FETCHER_ERROR_LOG_CLASS_NAME);
        return ClassName.get(unit.packageName(), unit.simpleName());
    }

    /** The nested {@code ErrorRouter.Mapping} interface every dispatch table is typed over. */
    public static ClassName mappingInterface(String outputPackage) {
        return routerClass(outputPackage).nestedClass(MAPPING_INTERFACE);
    }

    public static List<TypeSpec> generate(String outputPackage) {
        var typeP = TypeVariableName.get("P");
        var resultOfP = ParameterizedTypeName.get(DATA_FETCHER_RESULT, typeP);

        var mappingInterface = buildMappingInterface();

        var exceptionMapping = buildExceptionMapping();
        var sqlStateMapping = buildSqlStateMapping();
        var vendorCodeMapping = buildVendorCodeMapping();

        var loggerField = FieldSpec.builder(LOGGER_CN, "LOGGER",
                Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL)
            .initializer("$T.getLogger($L.class)", LOGGER_FACTORY_CN, CLASS_NAME)
            .build();

        var redact = MethodSpec.methodBuilder("redact")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addTypeVariable(typeP)
            .returns(resultOfP)
            .addParameter(THROWABLE, "thrown")
            .addParameter(DATA_FETCHING_ENVIRONMENT, "env")
            .addJavadoc("No-channel disposition: mints a fresh UUID correlation ID, hands the original\n"
                + "throw to the configured {@code FetcherErrorLog} (else logs it at ERROR), and returns\n"
                + "a {@link $T} with {@code data=null} plus a single redacted error carrying only the\n"
                + "correlation ID. Generic on {@code P},\n"
                + "the field's data type; the call site infers {@code P} from its target type so\n"
                + "the catch arm fits the fetcher's declared return type without a witness.\n"
                + "\n"
                + "<p>The raw exception message is never put into the response. This is the\n"
                + "privacy property the rewrite preserves at the fetcher catch site (see\n"
                + "{@code error-handling-parity.md} §3 \"No top-level handler\").\n",
                DATA_FETCHER_RESULT)
            .addCode(redactBody())
            .build();

        var toConfiguredLog = buildToConfiguredLogMethod(fetcherErrorLogClass(outputPackage));

        var surfaceClientErrorOrRedact = buildSurfaceClientErrorOrRedactMethod(typeP, resultOfP, outputPackage);
        var dispatch = buildDispatchMethod(typeP, resultOfP);

        var spec = TypeSpec.classBuilder(CLASS_NAME)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Runtime entry points for the per-fetcher exception-handling wrappers emitted\n"
                + "by Graphitron. Every emitted fetcher wraps its body in a try/catch (and an\n"
                + "{@code .exceptionally} arm for async fetchers) that funnels thrown exceptions\n"
                + "through this class: either to a channel-mapped typed payload\n"
                + "({@code dispatch}, with a {@code Mapping[]} constant from {@code ErrorMappings})\n"
                + "or, when there is no channel or no mapping claims the throw, to\n"
                + "{@code surfaceClientErrorOrRedact}: a client exception surfaces as a top-level\n"
                + "error, anything else becomes a redacted {@code DataFetcherResult} carrying only\n"
                + "a correlation ID ({@code redact}).\n"
                + "\n"
                + "<p>Generated alongside {@code ErrorMappings}; preserves the rewrite's\n"
                + "no-runtime-jar invariant.\n")
            .addField(loggerField)
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addType(mappingInterface)
            .addType(exceptionMapping)
            .addType(sqlStateMapping)
            .addType(vendorCodeMapping)
            .addMethod(redact)
            .addMethod(toConfiguredLog)
            .addMethod(surfaceClientErrorOrRedact)
            .addMethod(dispatch)
            .build();

        return List.of(spec);
    }

    /** No-arg overload for tests that don't exercise cross-class refs. */
    public static List<TypeSpec> generate() {
        return generate("");
    }

    /**
     * The one definition of the no-channel error disposition:
     * {@code ErrorRouter.surfaceClientErrorOrRedact(<throwableVar>, env)}. Every no-channel emit
     * site (sync catch arms and async {@code .exceptionally} arms) consults this helper, so a
     * disposition change is one edit, not a multi-site coordination.
     */
    public static CodeBlock noChannelRouterCall(String outputPackage, String throwableVar) {
        return no.sikt.graphitron.render.ErrorDispatchFragments.redact(
            routerClass(outputPackage), throwableVar);
    }

    private static TypeSpec buildMappingInterface() {
        var match = MethodSpec.methodBuilder("match")
            .addModifiers(Modifier.PUBLIC, Modifier.ABSTRACT)
            .returns(boolean.class)
            .addParameter(THROWABLE, "throwable")
            .addJavadoc("Whether this mapping's criteria fire on {@code throwable}. The dispatch arm\n"
                + "walks the cause chain outermost-first per mapping; the first match wins.\n")
            .build();

        var description = MethodSpec.methodBuilder("description")
            .addModifiers(Modifier.PUBLIC, Modifier.ABSTRACT)
            .returns(STRING_CN)
            .addJavadoc("The {@code description} from the {@code @error} declaration, or {@code null}\n"
                + "when none was set. Read by the {@code message} method on the matching\n"
                + "{@code <ErrorType>Fetchers} class, which walks its own type's dispatch table and\n"
                + "returns this string in place of the source's own message on a match. The matched\n"
                + "source object is never wrapped or substituted: the source-direct contract is what\n"
                + "keeps the union {@code TypeResolver} and the extra fields'\n"
                + "{@code PropertyDataFetcher} reads pointed at the author's own exception.\n")
            .build();

        return TypeSpec.interfaceBuilder(MAPPING_INTERFACE)
            .addModifiers(Modifier.PUBLIC)
            .addJavadoc("One channel-flattened entry on the per-fetcher {@code Mapping[]} array. Each\n"
                + "concrete variant ({@link ExceptionMapping}, {@link SqlStateMapping},\n"
                + "{@link VendorCodeMapping}) implements {@link #match(Throwable)} against the\n"
                + "thrown cause. No {@code build} factory: under the source-direct dispatch\n"
                + "contract the matched throwable itself goes into the errors list, and\n"
                + "graphql-java's {@code PropertyDataFetcher} reads each declared {@code @error}\n"
                + "field directly from the source.\n")
            .addMethod(match)
            .addMethod(description)
            .build();
    }

    private static TypeSpec buildExceptionMapping() {
        var classOfThrowable = ParameterizedTypeName.get(
            ClassName.get(Class.class), WildcardTypeName.subtypeOf(THROWABLE));

        return TypeSpec.classBuilder(EXCEPTION_MAPPING)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
            .addSuperinterface(ClassName.get("", MAPPING_INTERFACE))
            .addJavadoc("Matches by exception class identity. Lift target for\n"
                + "{@code @error} {@code GENERIC} handlers and the no-discriminator {@code DATABASE}\n"
                + "handler (which lifts to {@code ExceptionMapping(SQLException, ...)}).\n")
            .addField(FieldSpec.builder(classOfThrowable, "exceptionClass",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "matches",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "description",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addMethod(MethodSpec.constructorBuilder()
                .addModifiers(Modifier.PUBLIC)
                .addParameter(classOfThrowable, "exceptionClass")
                .addParameter(STRING_CN, "matches")
                .addParameter(STRING_CN, "description")
                .addStatement("this.exceptionClass = exceptionClass")
                .addStatement("this.matches = matches")
                .addStatement("this.description = description")
                .build())
            .addMethod(MethodSpec.methodBuilder("match")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(boolean.class)
                .addParameter(THROWABLE, "throwable")
                .addCode("if (!exceptionClass.isInstance(throwable)) return false;\n")
                .addCode("if (matches == null) return true;\n")
                .addCode("$T msg = throwable.getMessage();\n", STRING_CN)
                .addCode("return msg != null && msg.contains(matches);\n")
                .build())
            .addMethod(MethodSpec.methodBuilder("description")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(STRING_CN)
                .addStatement("return description")
                .build())
            .build();
    }

    private static TypeSpec buildSqlStateMapping() {
        return TypeSpec.classBuilder(SQL_STATE_MAPPING)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
            .addSuperinterface(ClassName.get("", MAPPING_INTERFACE))
            .addJavadoc("Matches any {@link $T} in the cause chain whose {@code getSQLState()} equals\n"
                + "the configured {@code sqlState}. Lift target for\n"
                + "{@code @error} {@code DATABASE} handlers with {@code sqlState} set.\n", SQL_EXCEPTION)
            .addField(FieldSpec.builder(STRING_CN, "sqlState",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "matches",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "description",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addMethod(MethodSpec.constructorBuilder()
                .addModifiers(Modifier.PUBLIC)
                .addParameter(STRING_CN, "sqlState")
                .addParameter(STRING_CN, "matches")
                .addParameter(STRING_CN, "description")
                .addStatement("this.sqlState = sqlState")
                .addStatement("this.matches = matches")
                .addStatement("this.description = description")
                .build())
            .addMethod(MethodSpec.methodBuilder("match")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(boolean.class)
                .addParameter(THROWABLE, "throwable")
                .addCode("if (!(throwable instanceof $T sqlEx)) return false;\n", SQL_EXCEPTION)
                .addCode("if (!sqlState.equals(sqlEx.getSQLState())) return false;\n")
                .addCode("if (matches == null) return true;\n")
                .addCode("$T msg = throwable.getMessage();\n", STRING_CN)
                .addCode("return msg != null && msg.contains(matches);\n")
                .build())
            .addMethod(MethodSpec.methodBuilder("description")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(STRING_CN)
                .addStatement("return description")
                .build())
            .build();
    }

    private static TypeSpec buildVendorCodeMapping() {
        return TypeSpec.classBuilder(VENDOR_CODE_MAPPING)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
            .addSuperinterface(ClassName.get("", MAPPING_INTERFACE))
            .addJavadoc("Matches any {@link $T} in the cause chain whose {@code getErrorCode()}\n"
                + "string-equals the configured {@code vendorCode}. Lift target for\n"
                + "{@code @error} {@code DATABASE} handlers with {@code code} set.\n", SQL_EXCEPTION)
            .addField(FieldSpec.builder(STRING_CN, "vendorCode",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "matches",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addField(FieldSpec.builder(STRING_CN, "description",
                Modifier.PRIVATE, Modifier.FINAL).build())
            .addMethod(MethodSpec.constructorBuilder()
                .addModifiers(Modifier.PUBLIC)
                .addParameter(STRING_CN, "vendorCode")
                .addParameter(STRING_CN, "matches")
                .addParameter(STRING_CN, "description")
                .addStatement("this.vendorCode = vendorCode")
                .addStatement("this.matches = matches")
                .addStatement("this.description = description")
                .build())
            .addMethod(MethodSpec.methodBuilder("match")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(boolean.class)
                .addParameter(THROWABLE, "throwable")
                .addCode("if (!(throwable instanceof $T sqlEx)) return false;\n", SQL_EXCEPTION)
                .addCode("if (!vendorCode.equals($T.valueOf(sqlEx.getErrorCode()))) return false;\n", STRING_CN)
                .addCode("if (matches == null) return true;\n")
                .addCode("$T msg = throwable.getMessage();\n", STRING_CN)
                .addCode("return msg != null && msg.contains(matches);\n")
                .build())
            .addMethod(MethodSpec.methodBuilder("description")
                .addAnnotation(Override.class)
                .addModifiers(Modifier.PUBLIC)
                .returns(STRING_CN)
                .addStatement("return description")
                .build())
            .build();
    }

    private static MethodSpec buildSurfaceClientErrorOrRedactMethod(
            TypeVariableName typeP,
            ParameterizedTypeName resultOfP,
            String outputPackage) {
        var clientExceptionUnit = new no.sikt.graphitron.plan.GeneratedUnits(outputPackage).clientException();
        var clientException = ClassName.get(
            clientExceptionUnit.packageName(), clientExceptionUnit.simpleName());

        return MethodSpec.methodBuilder("surfaceClientErrorOrRedact")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addTypeVariable(typeP)
            .returns(resultOfP)
            .addParameter(THROWABLE, "thrown")
            .addParameter(DATA_FETCHING_ENVIRONMENT, "env")
            .addJavadoc("Unmatched disposition for every fetcher: the whole catch arm when the field\n"
                + "has no {@code @error} channel, and the fall-through after the channel's mappings\n"
                + "when it has one and none claims the throw. Walks the cause chain\n"
                + "outermost-first; if a {@link $T} (itself a {@code GraphQLError}) is found,\n"
                + "returns a {@link $T} with {@code data=null} and that error, so the real\n"
                + "client-facing message reaches the response {@code errors} array. On no match\n"
                + "falls through to {@link #redact}: genuine internal faults keep the privacy\n"
                + "contract (logged + correlation id only).\n"
                + "\n"
                + "<p>Surfacing is narrowed to the client-error marker type, so an unclaimed client\n"
                + "error reads the same with or without a channel, while an authored mapping that\n"
                + "matches it still places it into the payload.\n",
                clientException, DATA_FETCHER_RESULT)
            .addCode(CodeBlock.builder()
                .beginControlFlow("for ($T t = thrown; t != null; t = t.getCause())", THROWABLE)
                .beginControlFlow("if (t instanceof $T clientError)", clientException)
                .addStatement("return $T.<P>newResult().data(null).error(clientError).build()", DATA_FETCHER_RESULT)
                .endControlFlow()
                .endControlFlow()
                .addStatement("return redact(thrown, env)")
                .build())
            .build();
    }

    private static MethodSpec buildDispatchMethod(
            TypeVariableName typeP,
            ParameterizedTypeName resultOfP) {
        var mapping = ClassName.get("", MAPPING_INTERFACE);
        var mappingArray = ArrayTypeName.of(mapping);
        var listOfWildcard = ParameterizedTypeName.get(LIST_CN, WildcardTypeName.subtypeOf(OBJECT_CN));
        var payloadFactoryType = ParameterizedTypeName.get(ClassName.get(Function.class),
            listOfWildcard, typeP);

        return MethodSpec.methodBuilder("dispatch")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addTypeVariable(typeP)
            .returns(resultOfP)
            .addParameter(THROWABLE, "thrown")
            .addParameter(mappingArray, "mappings")
            .addParameter(DATA_FETCHING_ENVIRONMENT, "env")
            .addParameter(payloadFactoryType, "payloadFactory")
            .addJavadoc("Channel-mapped dispatch (source-direct contract). For each mapping in\n"
                + "source-declaration order, walks the cause chain outermost-first; the first\n"
                + "match places the matched {@code Throwable} itself into the errors list and\n"
                + "returns the populated payload. Falls through to {@link #surfaceClientErrorOrRedact}\n"
                + "on no match, the disposition a fetcher without a channel gets.\n"
                + "graphql-java's {@code PropertyDataFetcher} reads each declared {@code @error}\n"
                + "field directly from whatever source object happens to be in the slot;\n"
                + "per-channel {@code TypeResolver}s dispatch each source to its SDL\n"
                + "{@code @error} type at serialisation time.\n"
                + "\n"
                + "<p>{@code ValidationHandler} entries produce no {@code Mapping} and never\n"
                + "reach this method: the wrapper invokes {@code jakarta.validation.Validator}\n"
                + "as a pre-execution step and routes the resulting\n"
                + "{@code GraphQLError}s directly into the errors slot.\n"
                + "\n"
                + "<p>The {@code description} field on each {@link Mapping} is not consulted here.\n"
                + "It is read on the fetch side, by the {@code message} method of the\n"
                + "{@code <ErrorType>Fetchers} class for the type the {@code TypeResolver} selected,\n"
                + "so an authored override cannot disagree with the {@code __typename} the client\n"
                + "sees in the same selection set.\n")
            // ----- Source-order match -----
            .addCode("// Source-order match: first (mapping, cause) pair that satisfies the predicate.\n")
            .beginControlFlow("for ($T mapping : mappings)", mapping)
            .beginControlFlow("for ($T t = thrown; t != null; t = t.getCause())", THROWABLE)
            .beginControlFlow("if (mapping.match(t))")
            .addStatement("return $T.<P>newResult().data(payloadFactory.apply($T.of(t))).build()",
                DATA_FETCHER_RESULT, LIST_CN)
            .endControlFlow()
            .endControlFlow()
            .endControlFlow()
            // ----- Unmatched: surface a client error, else redact -----
            .addCode("\n// Unmatched: surface a client error, else log + redacted DataFetcherResult.\n")
            .addStatement("return surfaceClientErrorOrRedact(thrown, env)")
            .build();
    }

    /**
     * {@code static boolean toConfiguredLog(env, reference, call)}: the one spelling of the
     * {@code FetcherErrorLog} contract (look the log up, call it, contain its failure), shared by
     * {@code redact} and the tenant fan-out's failure logging. A {@code false} return means no
     * log is configured and the caller writes its own default line. The failure line passes no
     * throwable, so neither the log's exception nor the original reaches the log through it;
     * only JVM-fatal errors escape, since anything else escaping {@code redact} would reach
     * graphql-java's default handler, which puts its message in the response.
     */
    private static MethodSpec buildToConfiguredLogMethod(ClassName fetcherErrorLog) {
        return MethodSpec.methodBuilder("toConfiguredLog")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(boolean.class)
            .addParameter(DATA_FETCHING_ENVIRONMENT, "env")
            .addParameter(STRING_CN, "reference")
            .addParameter(ParameterizedTypeName.get(CONSUMER_CN, fetcherErrorLog), "call")
            .addJavadoc("Hands an unmatched throw to the {@link $T} configured for this request (the\n"
                + "{@code GraphQLContext} entry under its class, which the owned-connection runtime\n"
                + "publishes and an escape-hatch caller puts there); {@code false} when none is\n"
                + "configured, and the caller then logs its own default line. If the log throws, one\n"
                + "ERROR line names the log's class, the class of what it threw and the reference,\n"
                + "without either exception's message or stack trace; only a {@link VirtualMachineError}\n"
                + "propagates.\n"
                + "@param env the failing field's environment\n"
                + "@param reference the reference the client receives for this failure\n"
                + "@param call the log method to invoke\n"
                + "@return whether a configured log took the throw\n",
                fetcherErrorLog)
            .addStatement("$T context = env.getGraphQlContext()", GRAPHQL_CONTEXT)
            .addStatement("$T log = context == null ? null : context.get($T.class)", fetcherErrorLog, fetcherErrorLog)
            .beginControlFlow("if (log == null)")
            .addStatement("return false")
            .endControlFlow()
            .beginControlFlow("try")
            .addStatement("call.accept(log)")
            .nextControlFlow("catch ($T logFailure)", THROWABLE)
            .beginControlFlow("if (logFailure instanceof $T fatal)", VirtualMachineError.class)
            .addStatement("throw fatal")
            .endControlFlow()
            .addStatement("LOGGER.error($S, log.getClass().getName(), logFailure.getClass().getName(), reference)",
                fetcherErrorLog.simpleName() + " {} threw {}; reference = {}")
            .endControlFlow()
            .addStatement("return true")
            .build();
    }

    private static CodeBlock redactBody() {
        return CodeBlock.builder()
            .addStatement("$T correlationId = $T.randomUUID()", UUID_CN, UUID_CN)
            .addStatement("$T reference = correlationId.toString()", STRING_CN)
            .beginControlFlow("if (!toConfiguredLog(env, reference, log -> log.unmatched(thrown, reference, env)))")
            .addStatement("LOGGER.error(\"Unmatched exception in fetcher; correlation id = {}\", correlationId, thrown)")
            .endControlFlow()
            .add("return $T.<P>newResult()\n", DATA_FETCHER_RESULT)
            .add("    .data(null)\n")
            .add("    .error($T.newError(env)\n", GRAPHQL_ERROR_BUILDER)
            .add("        .message(\"An error occurred. Reference: \" + correlationId + \".\")\n")
            .add("        .build())\n")
            .addStatement("    .build()")
            .build();
    }
}
